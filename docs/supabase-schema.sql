CREATE POLICY "Public Update Services" ON public.services FOR UPDATE USING (true);
CREATE POLICY "Public Delete Services" ON public.services FOR DELETE USING (true);

CREATE POLICY "Public Read Barbers" ON public.barbers FOR SELECT USING (true);
CREATE POLICY "Public Insert Barbers" ON public.barbers FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Update Barbers" ON public.barbers FOR UPDATE USING (true);
CREATE POLICY "Public Delete Barbers" ON public.barbers FOR DELETE USING (true);

CREATE POLICY "Public Read Bookings" ON public.bookings FOR SELECT USING (true);
CREATE POLICY "Public Insert Bookings" ON public.bookings FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Update Bookings" ON public.bookings FOR UPDATE USING (true);

CREATE POLICY "Public Read Gallery" ON public.gallery FOR SELECT USING (true);
CREATE POLICY "Public Insert Gallery" ON public.gallery FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Update Gallery" ON public.gallery FOR UPDATE USING (true);
CREATE POLICY "Public Delete Gallery" ON public.gallery FOR DELETE USING (true);

